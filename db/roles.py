"""Login roles, column grants and row-level security, generated from db/access.yaml.

    uv run python -m db.roles [--dry-run] [--db NAME]

Idempotent: every run revokes everything the roles could reach, then grants exactly what
access.yaml says, so re-running converges the database to the file. Roles are cluster-wide;
grants and policies are per database, so run it once per database (make seed does).
"""
from __future__ import annotations

import argparse
import dataclasses
import re

import psycopg
from psycopg import sql

from sherpa.config import load_access, settings
from sherpa.contracts import Access

SCHEMAS = "raw, analytics, app"
PERSONA_SETTINGS = {"default_transaction_read_only": "on", "statement_timeout": "'5s'", "search_path": "analytics",
                    "temp_file_limit": "'512MB'"}   # superuser-only GUC: a persona cannot raise it; the disk is nearly full
# EXECUTE revoked from PUBLIC in each database (adversarial review R1, R8). Grants and RLS already protect rows;
# these close what is left: functions that run SQL passed as a string, touching other sessions, writing large
# objects, and server metadata. Nothing in the app calls them as a persona.
REVOKED_FUNCTIONS = [
    "ts_stat(text)", "ts_stat(text,text)", "ts_rewrite(tsquery,text)",
    "query_to_xml(text,boolean,boolean,text)", "query_to_xmlschema(text,boolean,boolean,text)",
    "query_to_xml_and_xmlschema(text,boolean,boolean,text)", "cursor_to_xml(refcursor,integer,boolean,boolean,text)",
    "cursor_to_xmlschema(refcursor,boolean,boolean,text)",
    "pg_cancel_backend(integer)", "pg_terminate_backend(integer,bigint)",
    "lo_create(oid)", "lo_creat(integer)", "lo_from_bytea(oid,bytea)", "lo_import(text)", "lo_import(text,oid)",
    "lo_export(oid,text)",
    "pg_sleep(double precision)", "pg_sleep_for(interval)", "pg_sleep_until(timestamp with time zone)",
    "current_setting(text)", "current_setting(text,boolean)", "pg_get_userbyid(oid)", "pg_relation_filepath(regclass)",
]
_IDENT = re.compile(r"^[a-z_][a-z0-9_]*$")


def _ident(name: str) -> str:
    # access.yaml is trusted config, but names still go into DDL unquoted, so refuse anything odd.
    if not _IDENT.match(name):
        raise ValueError(f"refusing identifier {name!r}")
    return name


def _lit(value: str) -> str:
    return sql.Literal(value).as_string(None)


def build_sql(access: Access, db_name: str, password: str) -> str:
    personas = [_ident(p.db_role) for p in access.personas.values()]
    app = _ident(access.app_role)
    everyone = ", ".join(["PUBLIC", *personas, app])
    readers = ", ".join(personas)
    out = ["-- generated by db/roles.py from db/access.yaml"]

    out.append("\n-- login roles (cluster-wide)")
    for role in [*personas, app]:
        out += [
            f"DO $$ BEGIN IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '{role}') "
            f"THEN CREATE ROLE {role}; END IF; END $$;",
            f"ALTER ROLE {role} WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS "
            f"NOINHERIT PASSWORD {_lit(password)};",
        ]
    # a role that can log in can ALTER ROLE itself (review R9): wipe every setting, then set ours
    for role in [*personas, app]:
        out += [f"ALTER ROLE {role} RESET ALL;", f"ALTER ROLE {role} IN DATABASE {_ident(db_name)} RESET ALL;"]
    for role in personas:
        out += [f"ALTER ROLE {role} SET {k} = {v};" for k, v in PERSONA_SETTINGS.items()]
    # a sherpa_* role no longer in access.yaml can no longer log in, and loses everything it held here (review R12)
    keep = ", ".join(f"'{r}'" for r in [*personas, app])
    out.append(
        "DO $$ DECLARE r text; BEGIN FOR r IN SELECT rolname FROM pg_roles WHERE rolname LIKE 'sherpa\\_%' "
        f"AND rolname <> ALL (ARRAY[{keep}]) LOOP EXECUTE format('ALTER ROLE %I NOLOGIN', r); "
        "EXECUTE format('DROP OWNED BY %I', r); END LOOP; END $$;"
    )

    out.append(f"\n-- start from nothing (database {_ident(db_name)})")
    out += [
        # our container only: nobody but the superuser connects to postgres/template1 (review R10)
        "REVOKE CONNECT, TEMPORARY ON DATABASE postgres, template1 FROM PUBLIC;",
        f"REVOKE CONNECT, TEMPORARY ON DATABASE {db_name} FROM PUBLIC;",
        f"GRANT CONNECT ON DATABASE {db_name} TO {', '.join([*personas, app])};",
        *(f"REVOKE EXECUTE ON FUNCTION pg_catalog.{f} FROM PUBLIC;" for f in REVOKED_FUNCTIONS),
        f"REVOKE ALL ON SCHEMA {SCHEMAS} FROM {everyone};",
        f"REVOKE ALL ON ALL TABLES IN SCHEMA {SCHEMAS} FROM {everyone};",  # also drops column grants
    ]

    out.append("\n-- personas: column-level SELECT on analytics only")
    out.append(f"GRANT USAGE ON SCHEMA analytics TO {readers};")
    for table, cols in access.exposed_tables.items():
        out.append(f"GRANT SELECT ({', '.join(map(_ident, cols))}) ON analytics.{_ident(table)} TO {readers};")

    out.append("\n-- row-level security on region (drop every analytics policy, then recreate)")
    out.append(
        "DO $$ DECLARE p record; BEGIN FOR p IN SELECT policyname, tablename FROM pg_policies "
        "WHERE schemaname = 'analytics' LOOP EXECUTE format('DROP POLICY %I ON analytics.%I', "
        "p.policyname, p.tablename); END LOOP; END $$;"
    )
    for table, cols in access.exposed_tables.items():
        if "region" not in cols:
            continue
        out += [
            f"ALTER TABLE analytics.{table} ENABLE ROW LEVEL SECURITY;",
            f"ALTER TABLE analytics.{table} FORCE ROW LEVEL SECURITY;",
        ]
        for p in access.personas.values():
            regions = ", ".join(_lit(r) for r in p.regions)
            out.append(
                f"CREATE POLICY {p.db_role}_region ON analytics.{table} FOR SELECT TO {p.db_role} "
                f"USING (region = ANY (ARRAY[{regions}]));"
            )

    out.append("\n-- app role: the run log and its feedback, insert-only (no UPDATE or DELETE)")
    out += [f"GRANT USAGE ON SCHEMA app TO {app};", f"GRANT INSERT, SELECT ON app.runs, app.run_feedback TO {app};"]
    return "\n".join(out) + "\n"


def apply(db_name: str | None = None) -> None:
    s = settings()
    db_name = db_name or s.db_name
    script = build_sql(load_access(), db_name, s.role_password)
    with psycopg.connect(dataclasses.replace(s, db_name=db_name).admin_dsn()) as conn:
        conn.execute(script)  # one transaction: all or nothing


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--dry-run", action="store_true", help="print the SQL (password redacted) and exit")
    ap.add_argument("--db", default=None, help="database name (default: SHERPA_DB_NAME)")
    a = ap.parse_args()
    if a.dry_run:
        print(build_sql(load_access(), a.db or settings().db_name, "<SHERPA_ROLE_PASSWORD>"), end="")
        return
    if not settings().role_password:
        raise SystemExit("SHERPA_ROLE_PASSWORD is empty; set it in .env")
    apply(a.db)
    print(f"roles applied to {a.db or settings().db_name}")


if __name__ == "__main__":
    main()
